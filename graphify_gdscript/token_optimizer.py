"""Token Consumption Optimizer & GraphRAG Traversal Engine for Godot.

Reduces LLM API token consumption by up to 99% by replacing massive whole-codebase
dumps with targeted, high-density knowledge subgraphs.
"""
from __future__ import annotations

import math
import re
from typing import Any, Dict, List, Optional, Set, Tuple
import networkx as nx


class TokenReductionEngine:
    def __init__(self, graph: nx.DiGraph, total_raw_tokens: int = 0):
        self.graph = graph
        self.total_raw_tokens = total_raw_tokens or self._estimate_raw_tokens_from_graph()

    def _estimate_raw_tokens_from_graph(self) -> int:
        """Estimate naive whole-project dump token size from source files."""
        unique_files: Set[str] = set()
        for nid in self.graph.nodes:
            src = self.graph.nodes[nid].get("source_file")
            if src:
                unique_files.add(src)

        total_words = 0
        for f in unique_files:
            try:
                with open(f, "r", encoding="utf-8", errors="replace") as fp:
                    total_words += len(fp.read().split())
            except Exception:
                pass
        return max(int(total_words * 1.35), 5000)

    def query(self, question: str, token_budget: int = 1500, mode: str = "bfs", depth: int = 2) -> Dict[str, Any]:
        """Query the knowledge graph for a targeted subgraph within a token budget.
        
        Args:
            question: natural language question or keyword query
            token_budget: maximum tokens allowed for the context snippet
            mode: 'bfs' (broad neighborhood) or 'dfs' (deep call chain)
            depth: traversal depth (1 to 4)
            
        Returns:
            Dictionary with targeted context, token savings, and matching nodes.
        """
        keywords = self._extract_keywords(question)
        seed_nodes = self._find_seed_nodes(keywords)

        if not seed_nodes:
            # Fallback to god nodes if no direct keyword match
            from graphify_gdscript.god_nodes import find_god_nodes
            gods = find_god_nodes(self.graph, top_k=3)
            seed_nodes = [g["id"] for g in gods]

        subgraph_nodes, subgraph_edges = self._traverse_subgraph(seed_nodes, depth=depth, mode=mode)
        
        # Build prompt-ready context constrained by token budget
        context_lines: List[str] = []
        context_lines.append(f"# Godot Knowledge Subgraph Context for: \"{question}\"")
        context_lines.append(f"> Auto-generated by graphify-gdscript (Budget: {token_budget} tokens)\n")

        # Group by files and classes
        files_map: Dict[str, List[dict]] = {}
        for nid in subgraph_nodes:
            data = self.graph.nodes.get(nid, {})
            sf = data.get("source_file", "unknown")
            files_map.setdefault(sf, []).append(data)

        # 1. Structural Overview
        context_lines.append("## Identified Relevant Components:")
        current_tokens = 40
        for sf, items in files_map.items():
            base_name = sf.replace("\\", "/").split("/")[-1]
            classes = [it["label"] for it in items if it.get("kind") in ("class", "scene", "autoload_singleton")]
            funcs = [it["label"] for it in items if it.get("kind") in ("function", "static_func", "signal_handler")]
            signals = [it["label"] for it in items if it.get("kind") in ("signal", "signal_ref")]
            
            line = f"- **{base_name}**"
            if classes:
                line += f" [{', '.join(classes)}]"
            if funcs:
                line += f" | Methods: {', '.join(funcs[:5])}"
            if signals:
                line += f" | Signals: {', '.join(signals[:3])}"
            context_lines.append(line)
            current_tokens += len(line.split()) * 2

        # 2. Key Signal Flows and Call Graphs
        context_lines.append("\n## Active Call & Signal Connections:")
        for edge in subgraph_edges:
            src_nid = edge["source"]
            tgt_nid = edge["target"]
            rel = edge.get("relation", "relates_to")
            ctx = edge.get("context")
            loc = edge.get("source_location", "")
            
            src_lbl = self.graph.nodes.get(src_nid, {}).get("label", src_nid)
            tgt_lbl = self.graph.nodes.get(tgt_nid, {}).get("label", tgt_nid)

            edge_str = f"- `{src_lbl}` --[{rel}]--> `{tgt_lbl}`"
            if loc:
                edge_str += f" ({loc})"
            if ctx:
                edge_str += f" [{ctx}]"

            context_lines.append(edge_str)
            current_tokens += len(edge_str.split()) * 2
            if current_tokens >= token_budget * 0.85:
                context_lines.append("- *(remaining minor connections truncated to preserve budget)*")
                break

        # 3. Direct Code References / Locations
        context_lines.append("\n## File Locations & Citations:")
        for nid in list(subgraph_nodes)[:15]:
            data = self.graph.nodes.get(nid, {})
            sf = data.get("source_file", "")
            loc = data.get("source_location", "")
            lbl = data.get("label", nid)
            kind = data.get("kind", "")
            if sf and loc:
                ref_line = f"- {lbl} ({kind}): `{sf}` at `{loc}`"
                context_lines.append(ref_line)
                current_tokens += len(ref_line.split()) * 2
                if current_tokens >= token_budget:
                    break

        full_context = "\n".join(context_lines)
        actual_tokens = int(len(full_context.split()) * 1.35)
        raw_tokens = self.total_raw_tokens
        tokens_saved = max(raw_tokens - actual_tokens, 0)
        reduction_pct = round((tokens_saved / max(raw_tokens, 1)) * 100, 2)

        # Standard pricing: ~$3.00 / 1M prompt tokens (blended average for flagship models)
        estimated_cost_saved = round((tokens_saved / 1_000_000.0) * 3.00, 4)

        return {
            "context": full_context,
            "actual_tokens": actual_tokens,
            "raw_project_tokens": raw_tokens,
            "tokens_saved": tokens_saved,
            "reduction_percentage": reduction_pct,
            "estimated_cost_saved_usd": estimated_cost_saved,
            "subgraph_nodes_count": len(subgraph_nodes),
            "subgraph_edges_count": len(subgraph_edges),
            "seed_nodes": seed_nodes,
        }

    def _extract_keywords(self, text: str) -> List[str]:
        """Extract search terms from question."""
        cleaned = re.sub(r"[^\w\s_]", " ", text.lower())
        stopwords = {
            "the", "a", "an", "in", "on", "at", "to", "for", "of", "with", "by",
            "is", "are", "was", "were", "and", "or", "how", "what", "where",
            "why", "which", "who", "does", "do", "can", "should", "code", "godot"
        }
        words = [w for w in cleaned.split() if len(w) > 1 and w not in stopwords]
        return words

    def _find_seed_nodes(self, keywords: List[str]) -> List[str]:
        """Match keywords against graph nodes."""
        scored: List[Tuple[str, int]] = []
        for nid, data in self.graph.nodes.items():
            label = data.get("label", "").lower()
            kind = data.get("kind", "").lower()
            src = data.get("source_file", "").lower()

            score = 0
            for kw in keywords:
                if kw == label:
                    score += 20
                elif kw in label:
                    score += 10
                elif kw in src:
                    score += 5
                elif kw in kind:
                    score += 2

            if score > 0:
                scored.append((nid, score))

        scored.sort(key=lambda x: x[1], reverse=True)
        return [item[0] for item in scored[:8]]

    def _traverse_subgraph(self, seeds: List[str], depth: int = 2, mode: str = "bfs") -> Tuple[Set[str], List[dict]]:
        """Collect neighborhood around seeds."""
        collected_nodes: Set[str] = set(seeds)
        collected_edges: List[dict] = []
        visited_edges: Set[Tuple[str, str, str]] = set()

        current_frontier = set(seeds)

        for d in range(depth):
            next_frontier = set()
            for n in current_frontier:
                if not self.graph.has_node(n):
                    continue

                # Outgoing edges
                for _, tgt, edata in self.graph.out_edges(n, data=True):
                    rel = edata.get("relation", "")
                    edge_key = (n, tgt, rel)
                    if edge_key not in visited_edges:
                        visited_edges.add(edge_key)
                        collected_edges.append(edata)
                    collected_nodes.add(tgt)
                    next_frontier.add(tgt)

                # Incoming edges
                for src, _, edata in self.graph.in_edges(n, data=True):
                    rel = edata.get("relation", "")
                    edge_key = (src, n, rel)
                    if edge_key not in visited_edges:
                        visited_edges.add(edge_key)
                        collected_edges.append(edata)
                    collected_nodes.add(src)
                    next_frontier.add(src)

            current_frontier = next_frontier
            if len(collected_nodes) > 40:
                break

        return collected_nodes, collected_edges
